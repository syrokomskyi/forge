import { parse as parseYaml, stringify as stringifyYaml } from "yaml";

import type { AuditFinding } from "./types.ts";

export const LEDGER_SCHEMA = "forge/correctness-ledger@1" as const;
export const DEFAULT_LEDGER_PATH = "docs/maintenance-debt/correctness.ledger.yaml";

export interface LedgerStamp {
  sha: string;
  date: string;
}

export interface LedgerRow {
  key: string;
  check: string;
  subject: string;
  firstSeen: LedgerStamp;
  lastSeen: LedgerStamp;
  status: "surviving" | "resolved";
}

export interface Ledger {
  schema: typeof LEDGER_SCHEMA;
  rows: LedgerRow[];
}

export function parseLedger(text: string | null): Ledger {
  if (!text) return { schema: LEDGER_SCHEMA, rows: [] };
  try {
    const doc = parseYaml(text) as { rows?: unknown };
    const rows = Array.isArray(doc?.rows)
      ? (doc.rows as LedgerRow[]).filter((r) => r && typeof r.key === "string")
      : [];
    return { schema: LEDGER_SCHEMA, rows };
  } catch {
    return { schema: LEDGER_SCHEMA, rows: [] };
  }
}

/**
 * Merge the current findings into the ledger: every current legacy/accepted
 * code finding is `surviving` with `lastSeen` = now (its `firstSeen` kept or
 * set to now); rows no longer present become `resolved` (their `lastSeen`
 * keeps the last revision that still had them).
 */
export function mergeLedger(
  previous: Ledger,
  findings: AuditFinding[],
  stamp: LedgerStamp,
): Ledger {
  const current = findings.filter(
    (f) =>
      f.check !== "bindings.verify.substance" &&
      (f.attribution === "legacy" || f.attribution === "accepted"),
  );
  const byKey = new Map(previous.rows.map((r) => [r.key, r]));
  const rows: LedgerRow[] = [];
  const seen = new Set<string>();
  for (const f of current) {
    const prior = byKey.get(f.key);
    rows.push({
      key: f.key,
      check: f.check,
      subject: f.subject,
      firstSeen: prior?.firstSeen ?? stamp,
      lastSeen: stamp,
      status: "surviving",
    });
    seen.add(f.key);
  }
  for (const r of previous.rows) {
    if (seen.has(r.key)) continue;
    rows.push({ ...r, status: "resolved" });
  }
  rows.sort((a, b) => a.check.localeCompare(b.check) || a.subject.localeCompare(b.subject));
  return { schema: LEDGER_SCHEMA, rows };
}

export function serializeLedger(ledger: Ledger): string {
  return (
    "# GENERATED by `forge correctness.audit --write-ledger` (RFC-1579) — survival of accepted correctness debt.\n" +
    stringifyYaml(ledger)
  );
}
