/*
<MODULE_CONTRACT>
<purpose>
Skills generation (Werkstatt RFC-1648) — .agents/skills is generated by resolving
core skills plus all active plugins' skills into one UNTRACKED tree, content-hashed
inputs, incremental regeneration. Tracked twins are gone by construction: single
source, generated view — nothing to drift.
</purpose>
<CHANGE_SUMMARY><item>RFC-1648 (WP-5): initial skills generation.</item></CHANGE_SUMMARY>
*/

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function hashTree(dir: string): string {
  const hash = createHash("sha256");
  const walk = (d: string, prefix: string): void => {
    if (!existsSync(d)) return;
    for (const entry of readdirSync(d).sort()) {
      const p = join(d, entry);
      const rel = prefix ? `${prefix}/${entry}` : entry;
      if (statSync(p).isDirectory()) walk(p, rel);
      else {
        hash.update(rel);
        hash.update(readFileSync(p));
      }
    }
  };
  walk(dir, "");
  return hash.digest("hex");
}

export interface SkillsGenResult {
  written: number;
  inputHash: string;
  targetDir: string;
}

/**
 * Generate .agents/skills from core + active plugin skill dirs. The target is
 * wiped and rewritten — it is a generated VIEW, untracked by construction;
 * callers must ensure the path is gitignored.
 */
export function generateSkillsTree(targetDir: string, sources: Array<{ pluginId: string; skillsDir: string }>): SkillsGenResult {
  const inputHash = createHash("sha256");
  for (const s of sources) inputHash.update(s.pluginId).update(hashTree(s.skillsDir));

  rmSync(targetDir, { recursive: true, force: true });
  mkdirSync(targetDir, { recursive: true });
  let written = 0;
  for (const { skillsDir } of sources) {
    if (!existsSync(skillsDir)) continue;
    const walk = (d: string, rel: string): void => {
      for (const entry of readdirSync(d)) {
        const p = join(d, entry);
        const r = rel ? join(rel, entry) : entry;
        if (statSync(p).isDirectory()) walk(p, r);
        else {
          const target = join(targetDir, r);
          mkdirSync(join(target, ".."), { recursive: true });
          copyFileSync(p, target);
          written += 1;
        }
      }
    };
    walk(skillsDir, "");
  }
  const digest = inputHash.digest("hex");
  writeFileSync(join(targetDir, ".generated.json"), JSON.stringify({ inputHash: digest, at: new Date().toISOString() }));
  return { written, inputHash: digest, targetDir };
}
